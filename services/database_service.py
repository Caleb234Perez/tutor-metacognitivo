import os
from datetime import datetime
import uuid

import psycopg2
from psycopg2.extras import RealDictCursor
from dotenv import load_dotenv


load_dotenv()

DATABASE_URL = os.getenv("DATABASE_URL")

def get_connection():
    """
    Crea y devuelve una conexión a PostgreSQL.
    """

    if not DATABASE_URL:
        raise RuntimeError(
            "No se encontró DATABASE_URL en las variables de entorno."
        )

    connection = psycopg2.connect(
        DATABASE_URL,
        cursor_factory=RealDictCursor,
    )

    return connection


def initialize_database():
    """
    Inicializa la base de datos PostgreSQL del prototipo
    y crea las tablas necesarias cuando no existen.
    """

    connection = get_connection()

    try:
        cursor = connection.cursor()

        # -------------------------------------------------
        # Tabla de participantes
        # -------------------------------------------------

        cursor.execute(
            """
            CREATE TABLE IF NOT EXISTS participants (
                participant_id TEXT PRIMARY KEY,
                created_at TEXT NOT NULL
            );
            """
        )

        # -------------------------------------------------
        # Tabla de sesiones
        # -------------------------------------------------

        cursor.execute(
            """
            CREATE TABLE IF NOT EXISTS sessions (
                session_id TEXT PRIMARY KEY,
                participant_id TEXT NOT NULL,
                start_time TEXT NOT NULL,
                end_time TEXT,
                duration_seconds INTEGER,
                interaction_count INTEGER DEFAULT 0,
                difficulty_count INTEGER DEFAULT 0,
                final_phase TEXT,
                status TEXT NOT NULL,

                FOREIGN KEY (participant_id)
                    REFERENCES participants(participant_id)
            );
            """
        )

        # -------------------------------------------------
        # Tabla de learning traces
        # -------------------------------------------------

        cursor.execute(
            """
            CREATE TABLE IF NOT EXISTS learning_traces (
                trace_id INTEGER GENERATED BY DEFAULT AS IDENTITY
                    PRIMARY KEY,
                session_id TEXT NOT NULL,
                timestamp TEXT NOT NULL,
                interaction_number INTEGER NOT NULL,
                student_message TEXT NOT NULL,
                activity_id TEXT,
                tutor_response TEXT NOT NULL,
                phase_before TEXT NOT NULL,
                phase_after TEXT NOT NULL,
                pedagogical_event TEXT NOT NULL,
                metacognitive_strategy TEXT NOT NULL,
                scaffolding_level INTEGER NOT NULL,
                difficulty_count INTEGER NOT NULL,

                FOREIGN KEY (session_id)
                    REFERENCES sessions(session_id),

                UNIQUE (
                    session_id,
                    interaction_number
                )
            );
            """
        )

        # -------------------------------------------------
        # Tabla de eventos técnicos
        # -------------------------------------------------

        cursor.execute(
            """
            CREATE TABLE IF NOT EXISTS technical_events (
                technical_event_id INTEGER
                    GENERATED BY DEFAULT AS IDENTITY
                    PRIMARY KEY,
                timestamp TEXT NOT NULL,
                session_id TEXT,
                participant_id TEXT,
                component TEXT NOT NULL,
                error_type TEXT NOT NULL,
                error_message TEXT,

                FOREIGN KEY (session_id)
                    REFERENCES sessions(session_id),

                FOREIGN KEY (participant_id)
                    REFERENCES participants(participant_id)
            );
            """
        )

        # -------------------------------------------------
        # Tabla de consentimientos
        # -------------------------------------------------

        cursor.execute(
            """
            CREATE TABLE IF NOT EXISTS participant_consents (
                consent_id INTEGER
                    GENERATED BY DEFAULT AS IDENTITY
                    PRIMARY KEY,
                participant_id TEXT NOT NULL,
                consent_version TEXT NOT NULL,
                consent_given INTEGER NOT NULL,
                consent_timestamp TEXT NOT NULL,

                FOREIGN KEY (participant_id)
                    REFERENCES participants(participant_id)
            );
            """
        )

        # -------------------------------------------------
        # Tabla de progreso de actividades
        # -------------------------------------------------

        cursor.execute(
            """
            CREATE TABLE IF NOT EXISTS participant_activity_progress (
                participant_id TEXT NOT NULL,
                activity_id TEXT NOT NULL,
                completed_at TEXT NOT NULL,

                PRIMARY KEY (
                    participant_id,
                    activity_id
                ),

                FOREIGN KEY (participant_id)
                    REFERENCES participants(participant_id)
            );
            """
        )

        connection.commit()

    finally:
        connection.close()
        
def create_participant(participant_id):
    """
    Registra un nuevo participante utilizando
    su identificador institucional.
    """

    initialize_database()

    participant_id = participant_id.strip()

    created_at = datetime.now().isoformat(
        timespec="seconds"
    )

    connection = get_connection()

    try:
        cursor = connection.cursor()

        cursor.execute(
            """
            INSERT INTO participants (
                participant_id,
                created_at
            )
            VALUES (%s, %s);
            """,
            (
                participant_id,
                created_at,
            ),
        )

        connection.commit()

    finally:
        connection.close()

    return participant_id


