def save_database_trace(
    session_id,
    interaction_number,
    student_message,
    activity_id,
    tutor_response,
    phase_before,
    phase_after,
    pedagogical_event,
    metacognitive_strategy,
    scaffolding_level,
    difficulty_count,
):
    """
    Guarda una learning trace asociada a una sesión.
    """

    timestamp = datetime.now().isoformat(
        timespec="seconds"
    )

    connection = get_connection()

    try:
        cursor = connection.cursor()

        cursor.execute(
            """
            INSERT INTO learning_traces (
                session_id,
                timestamp,
                interaction_number,
                student_message,
                activity_id,
                tutor_response,
                phase_before,
                phase_after,
                pedagogical_event,
                metacognitive_strategy,
                scaffolding_level,
                difficulty_count
            )
            VALUES (
                %s, %s, %s, %s, %s, %s,
                %s, %s, %s, %s, %s, %s
            )
            RETURNING trace_id;
            """,
            (
                session_id,
                timestamp,
                interaction_number,
                student_message,
                activity_id,
                tutor_response,
                phase_before,
                phase_after,
                pedagogical_event,
                metacognitive_strategy,
                scaffolding_level,
                difficulty_count,
            ),
        )

        trace_id = cursor.fetchone()["trace_id"]

        connection.commit()

    finally:
        connection.close()

    return trace_id


