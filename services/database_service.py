def mark_activity_completed(
    participant_id,
    activity_id,
):
    """
    Registra una actividad como completada por un participante.

    Si la actividad ya estaba registrada como completada,
    no crea un registro duplicado.
    """

    initialize_database()

    completed_at = datetime.now().isoformat(
        timespec="seconds"
    )

    connection = get_connection()

    try:
        cursor = connection.cursor()

        cursor.execute(
            """
            INSERT INTO participant_activity_progress (
                participant_id,
                activity_id,
                completed_at
            )
            VALUES (%s, %s, %s)
            ON CONFLICT (
                participant_id,
                activity_id
            )
            DO NOTHING;
            """,
            (
                participant_id,
                activity_id,
                completed_at,
            ),
        )

        connection.commit()

    finally:
        connection.close()


