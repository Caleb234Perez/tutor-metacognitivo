def abandon_database_session(
    session_id,
):
    """
    Marca como abandonada una sesión que permaneció
    activa debido a una interrupción inesperada.
    """

    connection = get_connection()

    try:
        cursor = connection.cursor()

        # Recuperar sesión activa
        cursor.execute(
            """
            SELECT
                start_time
            FROM sessions
            WHERE session_id = %s
              AND status = %s;
            """,
            (
                session_id,
                "active",
            ),
        )

        session_row = cursor.fetchone()

        if session_row is None:
            return False

        # Recuperar último rastro de la sesión
        cursor.execute(
            """
            SELECT
                interaction_number,
                difficulty_count,
                phase_after
            FROM learning_traces
            WHERE session_id = %s
            ORDER BY interaction_number DESC
            LIMIT 1;
            """,
            (session_id,),
        )

        last_trace = cursor.fetchone()

        # Reconstruir métricas disponibles
        if last_trace is not None:

            interaction_count = (
                last_trace["interaction_number"]
            )

            difficulty_count = (
                last_trace["difficulty_count"]
            )

            final_phase = (
                last_trace["phase_after"]
            )

        else:
            interaction_count = 0
            difficulty_count = 0
            final_phase = "planning"

        # Calcular duración
        end_datetime = datetime.now()

        start_datetime = datetime.fromisoformat(
            session_row["start_time"]
        )

        duration_seconds = int(
            (
                end_datetime
                - start_datetime
            ).total_seconds()
        )

        end_time = end_datetime.isoformat(
            timespec="seconds"
        )

        # Marcar sesión como abandonada
        cursor.execute(
            """
            UPDATE sessions
            SET
                end_time = %s,
                duration_seconds = %s,
                interaction_count = %s,
                difficulty_count = %s,
                final_phase = %s,
                status = %s
            WHERE session_id = %s
              AND status = %s;
            """,
            (
                end_time,
                duration_seconds,
                interaction_count,
                difficulty_count,
                final_phase,
                "abandoned",
                session_id,
                "active",
            ),
        )

        connection.commit()

        updated_rows = cursor.rowcount

    finally:
        connection.close()

    return updated_rows > 0


